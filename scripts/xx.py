# Noms de jeune fille (pour "née X")
NOMS_JEUNE_FILLE = NOMS_FAMILLE.copy()


def generate_patient_identity(rng: random.Random) -> Dict[str, str]:
    """
    Generate a diverse patient identity.
    ~95% female (reflecting breast cancer demographics).
    """
    is_female = rng.random() < 0.95
    
    if is_female:
        prenom = rng.choice(PRENOMS_FEMININS)
        nom = rng.choice(NOMS_FAMILLE)
        # 60% chance d'avoir un nom de jeune fille différent
        if rng.random() < 0.6:
            nom_jeune_fille = rng.choice([n for n in NOMS_JEUNE_FILLE if n != nom])
        else:
            nom_jeune_fille = None
        civilite = "Madame"
        sex = "F"
    else:
        prenom = rng.choice(PRENOMS_MASCULINS)
        nom = rng.choice(NOMS_FAMILLE)
        nom_jeune_fille = None
        civilite = "Monsieur"
        sex = "M"
    
    # Format the full name string for the prompt
    if nom_jeune_fille:
        full_name = f"{civilite} {nom.upper()} {prenom}, née {nom_jeune_fille.upper()}"
    else:
        full_name = f"{civilite} {nom.upper()} {prenom}"
    
    return {
        "civilite": civilite,
        "prenom": prenom,
        "nom": nom,
        "nom_jeune_fille": nom_jeune_fille,
        "full_name": full_name,
        "sex": sex,
    }


# =========================
# Conditioning (light) - V4
# =========================
def light_breast_profile(seed: int) -> Tuple[Dict[str, Any], Dict[str, str]]:
    """
    Returns:
      - fields_raw: typed values for template substitution
      - fields_str: strings exactly as we want them to appear (for checking)
    
    V4: Removed age, added patient name generation.
    """
    rng = random.Random(seed)
    
    # Generate patient identity
    identity = generate_patient_identity(rng)
    
    # Clinical variables
    side = rng.choice(["sein gauche", "sein droit"])
    subtype = rng.choice(["RH+/HER2-", "RH+/HER2+", "RH-/HER2+", "triple négatif"])
    stage = rng.choice(["cT1cN0M0", "cT2N0M0", "cT2N1M0", "cT3N0M0", "cT3N0M1", "cT3N1M0"])
    context = rng.choice(["adjuvant", "néoadjuvant", "récidive locale", "palliatif"])

    fields_raw = {
        "patient_name": identity["full_name"],
        "side": side,
        "subtype": subtype,
        "stage": stage,
        "context": context,
    }
    
    # Strings we want to enforce (and check) in the generated text
    # For patient name, we check for the surname (nom) in uppercase
    fields_str = {
        "patient_name": identity["nom"].upper(),  # Check if surname appears
        "prenom": identity["prenom"],  # Also track first name
        "side": side,
        "subtype": subtype,
        "stage": stage,
        "context": context,
        "sex": identity["sex"],
    }
    
    return fields_raw, fields_str


# =========================
# Simple mention checks (heuristics)
# =========================
def check_mentions(text: str, fields_str: Dict[str, str]) -> Dict[str, Any]:
    """
    Checks presence of exact strings (case-insensitive) with a small tolerance for context variants.
    V4: Removed age_ok, added patient_name_ok.
    """
    t = text.lower()
    t_original = text  # Keep original case for name check

    # Check patient name (surname should appear, case-insensitive for flexibility)
    patient_name_ok = fields_str["patient_name"].lower() in t
    
    side_ok = fields_str["side"].lower() in t
    subtype_ok = fields_str["subtype"].lower() in t
    stage_ok = fields_str["stage"].lower() in t

    context = fields_str["context"].lower()
    context_variants = {context}
    if context == "néoadjuvant":
        context_variants.update({"néoadjuvante", "neo-adjuvant", "néo-adjuvant", "néo adjuvant"})
    if context == "adjuvant":
        context_variants.update({"adjuvante"})
    if context == "palliatif":
        context_variants.update({"palliative", "palliatifs", "palliatives"})
    if context == "récidive locale":
        context_variants.update({
            "recidive locale",
            "récidive",
            "récidive locorégionale",
            "récidive loco-régionale",
            "récidive loco regionale",
        })

    context_ok = any(v in t for v in context_variants)
    
    # Check sex consistency (Madame/Monsieur)
    expected_sex = fields_str["sex"]
    if expected_sex == "F":
        sex_ok = "madame" in t or "mme" in t
    else:
        sex_ok = "monsieur" in t or "mr" in t or "m." in t

    flags = {
        "patient_name_ok": bool(patient_name_ok),
        "sex_ok": bool(sex_ok),
        "side_ok": bool(side_ok),
        "subtype_ok": bool(subtype_ok),
        "stage_ok": bool(stage_ok),
        "context_ok": bool(context_ok),
    }
    # Calculate mention rate (excluding sex_ok which is more of a consistency check)
    core_flags = [patient_name_ok, side_ok, subtype_ok, stage_ok, context_ok]
    mention_rate = sum(core_flags) / len(core_flags)
    flags["mention_rate"] = round(float(mention_rate), 3)
    return flags


# =========================
# Model loading
# =========================
def _auto_dtype() -> torch.dtype:
    if not torch.cuda.is_available():
        return torch.float32
    major, minor = torch.cuda.get_device_capability()
    # bf16 is generally safe on Ampere (8.0+) and newer; otherwise use fp16
    if major >= 8:
        return torch.bfloat16
    return torch.float16


def build_model(model_name: str, dtype: str = "auto"):
    # Tokenizer loading can fail on some clusters because of an old `tokenizers` version
    # unable to parse newer `tokenizer.json` files (common error: PyPreTokenizerTypeWrapper...).
    # We first try the fast tokenizer, then fall back to the slow tokenizer.
    try:
        tokenizer = AutoTokenizer.from_pretrained(
            model_name,
            trust_remote_code=True,
            use_fast=True,
        )
    except Exception as e_fast:
        print(f"[warn] Fast tokenizer load failed: {type(e_fast).__name__}: {e_fast}")
        print("[warn] Falling back to slow tokenizer (use_fast=False).")
        tokenizer = AutoTokenizer.from_pretrained(
            model_name,
            trust_remote_code=True,
            use_fast=False,
        )

    # Ensure pad token exists (important for some chat models)
    if tokenizer.pad_token is None and tokenizer.eos_token is not None:
        tokenizer.pad_token = tokenizer.eos_token

    if dtype == "auto":
        torch_dtype = _auto_dtype()
    else:
        dtype_map = {
            "fp16": torch.float16,
            "float16": torch.float16,
            "bf16": torch.bfloat16,
            "bfloat16": torch.bfloat16,
            "fp32": torch.float32,
            "float32": torch.float32,
        }
        if dtype not in dtype_map:
            raise ValueError(f"Unsupported --dtype '{dtype}'. Use: auto|fp16|bf16|fp32")
        torch_dtype = dtype_map[dtype]

    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype=torch_dtype,
        device_map="auto",
        trust_remote_code=True,
    )
    model.eval()
    return tokenizer, model


# =========================
# Prompt rendering
# =========================
def render_user_prompt(template: str, fields_raw: Dict[str, Any]) -> str:
    """
    Replace placeholders like {patient_name}, {side}, {subtype}, {stage}, {context}.
    We keep it strict: missing placeholder keys are an error to avoid silent bugs.
    """
    try:
        return template.format(**fields_raw)
    except KeyError as e:
        raise KeyError(f"Missing placeholder in user prompt template: {e}") from e


def build_messages(system_content: str, user_content: str) -> List[Dict[str, str]]:
    system_content = (system_content or "").strip()
    user_content = (user_content or "").strip()
    messages: List[Dict[str, str]] = []
    if system_content:
        messages.append({"role": "system", "content": system_content})
    messages.append({"role": "user", "content": user_content})
    return messages


# =========================
# Generation
# =========================
@torch.inference_mode()
def generate_one(
    tokenizer,
    model,
    mode: str,
    system_content: str,
    user_content: str,
    seed: int,
    max_new_tokens: int,
    temperature: float,
    top_p: float,
    repetition_penalty: float,
) -> str:
    # Repro
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    if mode == "chat":
        messages = build_messages(system_content, user_content)

        if hasattr(tokenizer, "apply_chat_template"):
            input_ids = tokenizer.apply_chat_template(
                messages,
                tokenize=True,
                add_generation_prompt=True,
                return_tensors="pt",
            ).to(model.device)
        else:
            # Fallback: simple concatenation
            flat = ""
            if system_content:
                flat += f"[SYSTEM]\n{system_content}\n\n"
            flat += f"[USER]\n{user_content}\n\n[ASSISTANT]\n"
            input_ids = tokenizer(flat, return_tensors="pt").input_ids.to(model.device)
    else:
        # plain mode: system + user concatenated
        flat = ""
        if system_content:
            flat += system_content.strip() + "\n\n"
        flat += user_content.strip()
        input_ids = tokenizer(flat, return_tensors="pt").input_ids.to(model.device)

    prompt_len = int(input_ids.shape[-1])

    out = model.generate(
        input_ids=input_ids,
        max_new_tokens=max_new_tokens,
        do_sample=True,
        temperature=temperature,
        top_p=top_p,
        repetition_penalty=repetition_penalty,
        eos_token_id=tokenizer.eos_token_id,
        pad_token_id=tokenizer.pad_token_id if tokenizer.pad_token_id is not None else tokenizer.eos_token_id,
    )

    gen_ids = out[0, prompt_len:]
    text = tokenizer.decode(gen_ids, skip_special_tokens=True).strip()

    # Small cleanup: remove leading role tags some models emit
    text = re.sub(r"^(assistant|assistant:)\s*", "", text, flags=re.IGNORECASE).strip()
    return text


# =========================
# Main
# =========================
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--mode", choices=["chat", "plain"], required=True)

    # Prompts
    ap.add_argument("--system_prompt", required=True, help="Path to system prompt (instructions only).")
    ap.add_argument("--user_prompt", required=True, help="Path to user prompt template (may contain {patient_name},{side},...).")

    # Output
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=30)
    ap.add_argument("--seed0", type=int, default=1000)

    # Generation params
    ap.add_argument("--max_new_tokens", type=int, default=1600)
    ap.add_argument("--temperature", type=float, default=0.4)
    ap.add_argument("--top_p", type=float, default=0.9)
    ap.add_argument("--repetition_penalty", type=float, default=1.1)
    ap.add_argument("--dtype", default="auto", help="auto|fp16|bf16|fp32")

    # Debug
    ap.add_argument("--print_messages", action="store_true", help="Print system/user messages for first sample.")
    ap.add_argument("--print_every", type=int, default=1, help="Log progress every k samples.")

    args = ap.parse_args()

    system_path = Path(args.system_prompt)
    user_path = Path(args.user_prompt)
    system_base = system_path.read_text(encoding="utf-8").strip()
    user_template = user_path.read_text(encoding="utf-8").strip()

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    tokenizer, model = build_model(args.model, dtype=args.dtype)
    print(f"[OK] Model loaded: {args.model} | mode={args.mode} | dtype={args.dtype}", flush=True)

    for i in range(args.n):
        seed = args.seed0 + i

        fields_raw, fields_str = light_breast_profile(seed)
        user_content = render_user_prompt(user_template, fields_raw)
        system_content = system_base

        if args.print_messages and i == 0:
            print("\n" + "=" * 80)
            print("[SYSTEM]")
            print(system_content)
            print("\n[USER]")
            print(user_content)
            print("=" * 80 + "\n", flush=True)

        t0 = time.time()
        text = generate_one(
            tokenizer=tokenizer,
            model=model,
            mode=args.mode,
            system_content=system_content,
            user_content=user_content,
            seed=seed,
            max_new_tokens=args.max_new_tokens,
            temperature=args.temperature,
            top_p=args.top_p,
            repetition_penalty=args.repetition_penalty,
        )
        dt = time.time() - t0

        mention_flags = check_mentions(text, fields_str)

        record = {
            "model": args.model,
            "prompt_file": {
                "system": system_path.name,
                "user": user_path.name,
            },
            "seed": seed,
            "gen_seconds_total": round(dt, 3),
            "system_content": system_content,
            "user_content": user_content,
            "fields": [
                fields_str["patient_name"],
                fields_str["sex"],
                fields_str["side"],
                fields_str["subtype"],
                fields_str["stage"],
                fields_str["context"],
            ],
            "profile_fields": fields_raw,
            **mention_flags,
            "cr_text": text,
        }

        with out_path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")

        if args.print_every > 0 and ((i + 1) % args.print_every == 0 or (i + 1) == args.n):
            print(
                f"[OK] {i+1}/{args.n} | {dt:.1f}s | mention_rate={mention_flags['mention_rate']} | name={fields_str['patient_name']} | sex={fields_str['sex']}",
                flush=True,
            )

    print(f"[DONE] Written to {out_path}", flush=True)


if __name__ == "__main__":
    main()